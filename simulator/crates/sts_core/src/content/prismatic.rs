/// `shop_card_content_id` for names without a hand-assigned id. Kept `const`
/// so card identities can be declared as constants.
#[must_use]
pub const fn pool_content_id(name: &str) -> ContentId {
    let bytes = name.as_bytes();
    let mut hash = 0u64;
    let mut index = 0;
    while index < bytes.len() {
        hash = hash.wrapping_mul(31).wrapping_add(bytes[index] as u64);
        index += 1;
    }
    ContentId::new(600u64.wrapping_add(hash))
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PrismaticCardSpec {
    pub definition: CardDefinition,
    /// Vanilla `AbstractCard.cardID`.
    pub source_card_id: &'static str,
    pub upgraded_cost: i8,
    pub damage_upgrade: i32,
    pub block_upgrade: i32,
    /// `baseMagicNumber`; zero when the card has none.
    pub magic: i32,
    pub magic_upgrade: i32,
    pub upgraded_keywords: CardKeywords,
}

impl PrismaticCardSpec {
    #[must_use]
    pub fn cost(&self, upgraded: bool) -> i8 {
        if upgraded {
            self.upgraded_cost
        } else {
            self.definition.cost
        }
    }

    #[must_use]
    pub fn damage(&self, upgraded: bool) -> i32 {
        self.definition.values.damage.unwrap_or(0) + if upgraded { self.damage_upgrade } else { 0 }
    }

    #[must_use]
    pub fn block(&self, upgraded: bool) -> i32 {
        self.definition.values.block.unwrap_or(0) + if upgraded { self.block_upgrade } else { 0 }
    }

    #[must_use]
    pub fn magic(&self, upgraded: bool) -> i32 {
        self.magic + if upgraded { self.magic_upgrade } else { 0 }
    }

    #[must_use]
    pub fn keywords(&self, upgraded: bool) -> CardKeywords {
        if upgraded {
            self.upgraded_keywords
        } else {
            self.definition.keywords
        }
    }
}

